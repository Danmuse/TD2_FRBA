/* USER CODE BEGIN 0 */
void taskEventTime(void *p)
{
	uint8_t msg = PARPADEAR;
	while(1)
	{
		vTaskDelay(pdMS_TO_TICKS(250));
		xQueueSend(mensajes_led, &msg, 0); // portMAX_DELAY);
	}
}

void taskButton(void *p)
{
	uint8_t msg = FREEZE;
	GPIO_PinState actual, anterior;
	anterior = HAL_GPIO_ReadPin(B1_GPIO_Port, B1_Pin);
	TickType_t tiempo_anterior = xTaskGetTickCount();

	while(1)
	{
		actual = HAL_GPIO_ReadPin(B1_GPIO_Port, B1_Pin);
		if (actual == GPIO_PIN_RESET && anterior == GPIO_PIN_SET) {
			TickType_t diff = xTaskGetTickCount() - tiempo_anterior;
			if (pdMS_TO_TICKS(diff) > 100) {
				tiempo_anterior = xTaskGetTickCount();
				xQueueSend(mensajes_led, &msg, portMAX_DELAY);
			}
		}
		anterior = actual;
		vTaskDelay(pdMS_TO_TICKS(10));
	}
}

void taskLed(void *p)
{
	uint8_t congela = 0;
	uint8_t rcv;
	while(1)
	{
		xQueueReceive(mensajes_led, &rcv, portMAX_DELAY);
		switch(rcv){
		case FREEZE:
			congela = !congela;
		case PARPADEAR:
			if (!congela) {
				HAL_GPIO_TogglePin(LD2_GPIO_Port, LD2_Pin);
			}
		default:
		}
	}
}

